"""Rebuild benchmarks/RESULTS.md (and the results block in README.md) from benchmarks/results/*.json.

    python benchmarks/make_table.py           # rewrite the files
    python benchmarks/make_table.py --check   # exit 1 if the committed files are out of date
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
MODELS = {'tfidf': 'TF-IDF + logistic regression', 'embeddings': 'MiniLM embeddings + logistic regression',
          'finetune': 'Fine-tuned ModernBERT-base'}
START, END = '<!-- results:start -->', '<!-- results:end -->'


def pct(x, digits=1):
    return '–' if x is None else f'{100 * x:.{digits}f}%'


def duration(seconds):
    return f'{seconds:.0f} s' if seconds < 90 else f'{seconds / 60:.0f} min'


def load():
    results = [json.loads(p.read_text()) for p in sorted((HERE / 'results').glob('*.json'))]
    return sorted(results, key=lambda r: (r['title'], list(MODELS).index(r['model'])))


def headline(results):
    lines = ['| Dataset | Model | Verdict | Coverage | Agreement on answered | 95% lower bound | Answering everything | Latency (median) | Training |',
             '|---|---|---|---|---|---|---|---|---|']
    for r in results:
        b = r['bars']['0.99']
        lines.append(f"| {r['title']} | {MODELS[r['model']]} | **{b['verdict']}** | {pct(b['coverage'])} | {pct(b['agreement'], 2)} | "
                     f"{pct(b['agreement_lower_bound'], 2)} | {pct(r['overall_accuracy'])} | {r['latency_ms']['p50']:.1f} ms | {duration(r['train_seconds'])} |")
    return lines


def other_bars(results):
    lines = ['| Dataset | Model | 99% bar | 95% bar | 90% bar |', '|---|---|---|---|---|']
    for r in results:
        cells = [f"{b['verdict']}: {pct(b['coverage'])} covered, bound {pct(b['agreement_lower_bound'], 2)}"
                 for b in (r['bars'][k] for k in ('0.99', '0.95', '0.90'))]
        lines.append(f"| {r['title']} | {MODELS[r['model']]} | " + ' | '.join(cells) + ' |')
    return lines


def datasets(results):
    lines = ['| Dataset | Rows | Labels | Sealed rows | Duplicate rows | Rows with conflicting labels | Labels with under 20 sealed rows |',
             '|---|---|---|---|---|---|---|']
    seen = set()
    for r in results:
        if r['dataset'] not in seen:
            seen.add(r['dataset'])
            lines.append(f"| {r['title']} | {r['rows']:,} | {r['labels']} | {r['sealed_rows']:,} | {r['duplicate_rows']:,} | "
                         f"{r['teacher_inconsistency_rows']:,} | {r['labels_unproven']} |")
    return lines


def weak_spots(results):
    lines = []
    for r in results:
        b = r['bars']['0.99']
        worst = [w for w in b['weakest_labels'] if w['accepted_disagreements'] or w['coverage'] < .5][:3]
        if not worst:
            continue
        parts = [f"`{w['label']}` ({w['accepted_disagreements']} wrong of {w['accepted']} answered, {pct(w['coverage'], 0)} covered)" for w in worst]
        never = f" {b['labels_never_accepted']} of {r['labels']} labels were never answered locally." if b['labels_never_accepted'] else ''
        lines.append(f"- **{r['title']}, {MODELS[r['model']]}:** " + '; '.join(parts) + '.' + never)
    return lines


def build():
    results = load()
    if not results:
        sys.exit('No result files in benchmarks/results; run benchmarks/run_benchmarks.py first')
    env = results[0]['environment']
    teachers = sorted({r['teacher'] for r in results})
    passes = sum(r['bars']['0.99']['verdict'] == 'PASS' for r in results)
    intro = [
        f"Teacher labels: **{'; '.join(teachers)}**. Bar: 95% Wilson lower bound on agreement of at least 99%, and at least "
        f"{pct(results[0]['min_coverage'], 0)} of calls answered locally. {passes} of {len(results)} dataset and model pairs pass.",
        '',
    ]
    short = intro + headline(results)
    full = ['# Benchmark results', '',
            'Generated by `python benchmarks/make_table.py` from the JSON files in `benchmarks/results/`. Do not edit by hand.',
            'Rerun everything from scratch with `python benchmarks/run_benchmarks.py` (downloads the datasets from their publishers).', '',
            '## At the default bar (99% agreement, 70% coverage)', '', *short, '',
            '- **Coverage**: share of sealed calls the local model answered; the rest would still go to the LLM.',
            '- **Agreement on answered**: how often the local answer equals the label in the data, on answered calls only.',
            '- **95% lower bound**: lower end of the 95% Wilson interval for that agreement. The verdict uses this, not the observed value.',
            '- **Answering everything**: agreement if the local model never abstained. The gap to "agreement on answered" is what abstaining buys.',
            f"- **Latency**: median time to classify one text on the benchmark machine ({env['system']} {env['machine']}, Python {env['python']}); "
            'the fine-tuned model ran on the Apple GPU (MPS). An LLM API call typically takes hundreds of milliseconds.',
            '- **Calls saved** per 1,000 equals coverage times 1,000. With the default assumptions ($0.50 per 1,000 calls, 3,000,000 calls '
            'a month, $20 a month to serve) the monthly saving is coverage × $1,500 − $20.', '',
            '## The same models at lower bars', '',
            'The threshold is re-chosen on the calibration split for each bar, then scored on the sealed split.', '', *other_bars(results), '',
            '## Weak spots at the 99% bar', '',
            'Labels where the local model was wrong on calls it chose to answer, or which it mostly declined to answer.', '', *weak_spots(results), '',
            '## Datasets', '', *datasets(results), '',
            '## How to read this honestly', '',
            '- These are human-labelled public datasets. The human labels stand in for "what the LLM answered". A real LLM teacher is '
            'noisier in some ways and more consistent in others, so your numbers will differ. Run it on your own logs.',
            '- One split and one seed per dataset: there are no error bars across seeds. The Wilson bound covers sampling error in the sealed '
            'split only.',
            '- The abstain threshold is chosen right at the edge of the bar on the calibration split, so a sealed lower bound that lands '
            'just under the bar (for example 94.4% against 95%) is common and counts as FAIL. That is intended: the sealed test is a '
            'confirmation, not a formality.',
            '- The sealed split of each dataset was scored once per model and bar. Nothing was tuned after looking at these numbers.',
            '- Fine-tuning on a GPU is not bit-for-bit repeatable. An earlier fine-tune of the same Banking77 split reached 45.8% '
            'coverage at the 99% bar; the run recorded here reached 39.7%. Expect differences of that size between reruns.', '']
    return '\n'.join(short), '\n'.join(full)


def main():
    short, full = build()
    readme_path, results_path = ROOT / 'README.md', HERE / 'RESULTS.md'
    readme = readme_path.read_text(encoding='utf-8')
    if START not in readme or END not in readme:
        sys.exit(f'README.md needs the markers {START} and {END}')
    new_readme = readme[:readme.index(START) + len(START)] + '\n' + short + '\n' + readme[readme.index(END):]
    if '--check' in sys.argv:
        stale = [p.name for p, text in ((readme_path, new_readme), (results_path, full))
                 if not p.exists() or p.read_text(encoding='utf-8') != text]
        if stale:
            sys.exit(f'Out of date: {", ".join(stale)}. Run python benchmarks/make_table.py')
        print('Results tables are up to date.')
        return
    readme_path.write_text(new_readme, encoding='utf-8')
    results_path.write_text(full, encoding='utf-8')
    print(f'Wrote {results_path.relative_to(ROOT)} and the results block in README.md')


if __name__ == '__main__':
    main()
